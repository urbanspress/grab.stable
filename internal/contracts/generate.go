func tsType(s Schema) string {
	t := "never"
	switch s.Type {
	case "text", "timestamp", "bytes":
		t = "string"
	case "integer":
		t = "GrabInteger"
	case "decimal":
		t = "GrabDecimal"
	case "boolean":
		t = "boolean"
	case "float":
		t = "number"
	case "nothing":
		t = "null"
	case "ref":
		t = "Types[" + quote(s.Ref) + "]"
	case "list":
		t = "Array<" + tsType(*s.Items) + ">"
	case "record":
		t = "{"
		for _, f := range s.Fields {
			q := ""
			if f.Optional {
				q = "?"
			}
			t += quote(f.Name) + q + ":" + tsType(f.Schema) + ";"
		}
		t += "}"
	}
	if s.Nullable && s.Type != "nothing" {
		t += " | null"
	}
	return t
}
