type ownership struct {
	Version int               `json:"version"`
	Files   map[string]string `json:"files"`
}

func digest(b []byte) string { h := sha256.Sum256(b); return hex.EncodeToString(h[:]) }

// Generate preflights every target before replacing any file. A previous hash,
// not merely a filename, proves ownership. Symlinks in every ancestor are refused.
func (d *Document) Generate(out string, react bool) error {
	root, e := filepath.Abs(out)
	if e != nil {
		return e
	}
	for p := root; ; p = filepath.Dir(p) {
		st, e := os.Lstat(p)
		if e == nil && st.Mode()&os.ModeSymlink != 0 {
			return fmt.Errorf("output contains symlink")
		}
		if e != nil && !os.IsNotExist(e) {
			return e
		}
		if filepath.Dir(p) == p {
			break
		}
	}
	files := d.Files(react)
	manifest := filepath.Join(root, ".grab-generated.json")
	old := ownership{Version: 1, Files: map[string]string{}}
	if st, e := os.Lstat(manifest); e == nil {
		if !st.Mode().IsRegular() {
			return fmt.Errorf("unsafe ownership manifest")
		}
		b, e := os.ReadFile(manifest)
		if e != nil || json.Unmarshal(b, &old) != nil || old.Version != 1 {
			return fmt.Errorf("invalid ownership manifest")
		}
	} else if !os.IsNotExist(e) {
		return e
	}
	for n, h := range old.Files {
		if filepath.Base(n) != n || n == ".grab-generated.json" {
			return fmt.Errorf("unsafe ownership entry")
		}
		b, e := os.ReadFile(filepath.Join(root, n))
		st, se := os.Lstat(filepath.Join(root, n))
		if e != nil || se != nil || !st.Mode().IsRegular() || digest(b) != h {
			return fmt.Errorf("generated file changed; refusing overwrite")
		}
	}
	for n := range files {
		st, e := os.Lstat(filepath.Join(root, n))
		if e == nil && (!st.Mode().IsRegular() || old.Files[n] == "") {
			return fmt.Errorf("refusing handwritten file or symlink")
		}
		if e != nil && !os.IsNotExist(e) {
			return e
		}
	}
	if e = os.MkdirAll(root, 0755); e != nil {
		return e
	}
	next := ownership{Version: 1, Files: map[string]string{}}
	for n, b := range files {
		next.Files[n] = digest(b)
	}
	b, _ := json.MarshalIndent(next, "", "  ")
	files[".grab-generated.json"] = append(b, '\n')
	names := make([]string, 0, len(files))
	for n := range files {
		if n != ".grab-generated.json" {
			names = append(names, n)
		}
	}
	sort.Strings(names)
	names = append(names, ".grab-generated.json")
	for _, n := range names {
		f, e := os.CreateTemp(root, ".grab-tmp-")
		if e != nil {
			return e
		}
		tmp := f.Name()
		_, e = f.Write(files[n])
		if e == nil {
			e = f.Sync()
		}
		ce := f.Close()
		if e == nil {
			e = ce
		}
		if e == nil {
			e = os.Rename(tmp, filepath.Join(root, n))
		}
		if e != nil {
			os.Remove(tmp)
			return e
		}
	}
	for n := range old.Files {
		if _, ok := files[n]; !ok {
			if e = os.Remove(filepath.Join(root, n)); e != nil {
				return e
			}
		}
	}
	return nil
}

